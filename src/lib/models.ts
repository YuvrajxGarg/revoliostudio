/**
 * Model registry — maps Revolio's internal model catalog to real muapi.ai
 * endpoint slugs. Verified against muapi's official CLI source
 * (T2I_MODELS / I2I_MODELS / T2V_MODELS / I2V_MODELS in muapi-cli).
 *
 * To add a new muapi model later: add one entry here. Nothing else in the
 * app needs to change — the composer, studio pages, and API routes all
 * read from this registry.
 */

export type Category = "image" | "video" | "3d" | "audio";
export type Mode =
  | "t2i"
  | "i2i"
  | "t2v"
  | "i2v"
  | "flf"
  | "omni"
  | "t23d"
  | "i23d"
  | "enhance"
  | "v2v"
  | "motion"
  /** Text-to-audio — full songs (Suno) or short sound effects / Foley (MMAudio). */
  | "t2a";
export type ImageInputKey = "image_url" | "images_list";

export interface ModelConfig {
  id: string;
  label: string;
  provider: string;
  category: Category;
  mode: Mode;
  endpoint: string;
  /**
   * Override for the actual job-submission POST endpoint, when it differs
   * from `endpoint` (which doubles as the GET /models/{slug} catalog/schema
   * lookup key). Confirmed necessary for at least the ByteDance Seedream
   * 5.0 family on muapi: their catalog + schema is keyed by the full
   * provider-prefixed name (e.g. "bytedance-seedream-5.0-pro-edit"), but
   * muapi's own published API docs for that model show the real submission
   * route as `POST /api/v1/seedream-5.0-pro-edit` — no "bytedance-" prefix.
   * Every muapi model schema also nests a nearly-identical-looking
   * "endpoint_url" field under input_schema that, for this family, matches
   * this shorter unprefixed form — that's the tell for which other models
   * need this override. When unset, `endpoint` is used for both purposes
   * (true for the vast majority of the catalog).
   */
  submitEndpoint?: string;
  /** How reference/source images are sent to muapi for this endpoint. */
  imageInputKey?: ImageInputKey;
  /** Max number of reference images this endpoint accepts. */
  maxReferences: number;
  /** Supports a distinct start-frame + end-frame pair (video only). */
  supportsStartEndFrame?: boolean;
  /**
   * Only set on `supportsStartEndFrame` models whose real schema sends the
   * end frame as its own named field (e.g. Kling v3 4K's "last_image")
   * rather than a second entry in `images_list`. When unset, a
   * `supportsStartEndFrame` model is assumed to take images_list = [start,
   * end] (same shape as the dedicated "flf" mode models).
   */
  endFrameFieldName?: string;
  aspectRatios?: string[];
  defaultAspectRatio?: string;
  durations?: number[];
  defaultDuration?: number;
  supportsNumImages?: boolean;
  maxNumImages?: number;
  /** True for models whose primary input is a video (Edit Video / Motion Control), not text or an image. */
  requiresVideoInput?: boolean;
  /** True for "motion" mode models that need a separate character image alongside the motion video. */
  requiresCharacterImage?: boolean;
  /**
   * The muapi field name for the primary input video. Used by two modes:
   *   - `mode: "motion"` models whose motion/reference video isn't under the
   *     default "reference_video_url" (e.g. Wan Animate's "video_url").
   *   - `mode: "v2v"` (Edit Video) models whose source-video field isn't the
   *     default "video_url" (e.g. Seedance 2.0 Video Edit's "video_urls").
   * When unset, motion mode uses "reference_video_url" and v2v uses
   * "video_url" — the historical defaults for each.
   */
  videoFieldName?: string;
  /**
   * `mode: "v2v"` only: the primary video field is an array of URLs rather
   * than a single string (e.g. Seedance 2.0 Video Edit's `video_urls`, which
   * takes max 1 item). The single uploaded video is wrapped in a one-element
   * array before submitting. When unset, the video is sent as a bare string.
   */
  videoInputIsArray?: boolean;
  /**
   * `mode: "v2v"` only: whether the model's schema has a `keep_original_sound`
   * field. Most Edit Video models do; Seedance's video-edit does not (it
   * handles audio via a separate `audio_files` input), so its "Keep original
   * sound" toggle is hidden and the field is never submitted. Defaults to
   * true (field sent) when unset, preserving existing models' behavior.
   */
  supportsKeepSound?: boolean;
  /**
   * Most `mode: "motion"` models (Runway Act-Two) ignore prompt entirely —
   * it's stripped from the payload. Set this when a motion model actually
   * accepts an optional prompt to guide the result (Wan Animate does).
   */
  motionSupportsPrompt?: boolean;
  /**
   * For `mode: "motion"` models with a real "mode" enum beyond the base
   * character-image + motion-video inputs — e.g. Wan Animate's
   * "animate" (pose-transfer only) vs "replace" (swap the video's
   * character for your image's). Exposed as a toggle in Motion Control;
   * whichever value is selected is sent under the literal `mode` field.
   */
  motionModeOptions?: { value: string; label: string; description: string }[];
  defaultMotionMode?: string;
  /**
   * For `mode: "motion"` models with a selectable output resolution (e.g.
   * Wan Animate's 480p/720p, priced 2x apart) — exposed as a toggle in
   * Motion Control, sent under the generic `settings.resolution` path
   * (same as every other model's resolution control).
   */
  motionResolutionOptions?: string[];
  defaultMotionResolution?: string;
  /** Discrete upscale-factor choices (Topaz image upscaler). */
  upscaleFactors?: number[];
  defaultUpscaleFactor?: number;
  badge?: string;
  /** Shown in the "Popular" pinned section at the top of the model picker. */
  popular?: boolean;
  /**
   * Shown in the "Recommended" pinned section (under Favorites, above
   * Popular) — our own curated pick of the cheap-but-good models worth
   * defaulting to, as opposed to `popular` which just tracks demand.
   */
  recommended?: boolean;
  /**
   * Set when a model is confirmed broken on muapi's own side (not
   * something a code fix here can resolve) — e.g. their job-submission
   * endpoint 404ing despite a healthy schema and a working web-app flow.
   * The picker greys the row out and blocks selection; generate.ts also
   * rejects a submit server-side as a backstop. Remove this flag once
   * muapi confirms the endpoint is fixed.
   */
  unavailable?: boolean;
  /** Shown as a tooltip on the disabled row when `unavailable` is set. */
  unavailableReason?: string;
  /**
   * Set when this model isn't actually a muapi endpoint at all — generate.ts
   * routes these to a dedicated integration instead of submitJob/getResult.
   * Currently only "photoroom" (Remove Background, `/v1/segment`): a
   * synchronous call that returns image bytes directly rather than a
   * request_id to poll, so `endpoint` on these entries is unused/descriptive
   * only.
   */
  externalProvider?: "photoroom";
  /**
   * True for edit models confirmed (or believed, pending live verification —
   * see the "Inpaint" doc comment on GenerateBody in generate.ts) to accept
   * an optional mask image alongside the source image, restricting the edit
   * to the painted region. Gates which models Inpaint's model picker offers
   * — generate.ts still probes the model's real live schema at submit time
   * to find the actual field name rather than guessing one blind.
   */
  supportsMask?: boolean;
  tagline: string;
}

