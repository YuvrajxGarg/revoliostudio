/**
 * Curated "select a template, fill in the inputs, run" presets — Revolio's
 * answer to Higgsfield/Magnific's Motion Controls/Templates page.
 *
 * Every entry here is modeled directly on a real Higgsfield preset — pulled
 * from the Higgsfield MCP's `presets_show` tool and from browsing
 * higgsfield.ai's own preset pickers and public `/effects` preset pages
 * (Basic Camera Control, Epic Camera Control, Catch the Pulse, Mix, and the
 * Soul 2.0 image "moodboard" styles). Where Higgsfield publishes an official
 * one-line description for an effect (via `presets_show` or its public
 * `/motion/<id>` pages), that description is the basis for the prompt below,
 * rewritten to run cleanly against our own muapi-backed models — Higgsfield's
 * presets are closed preset IDs / LoRA-style motion modules we can't call
 * directly, so every prompt here is our own text, written to reproduce the
 * same look. Higgsfield's own preview media is never linked or embedded here
 * (see the reference docs delivered earlier) — every card falls back to the
 * icon+gradient placeholder unless it reuses one of our 4 original
 * hand-picked local preview clips.
 *
 * Every `modelId` here must exist in MODELS and be runnable as-is — this
 * file intentionally does not invent new muapi endpoints, only curates
 * prompts/settings on top of ones already verified working.
 */

export type PresetGroup =
  | "Motion Control"
  | "Viral Effects"
  | "Catch the Pulse"
  | "Mix Effects"
  | "Image Styles";

export interface PresetTemplate {
  id: string;
  group: PresetGroup;
  title: string;
  description: string;
  studioCategory: Category;
  modelId: string;
  /** Video studio tab this preset belongs in — irrelevant for image/3d. */
  tab?: "create" | "edit" | "motion";
  /** Pre-filled prompt. Left undefined for presets where the model needs no prompt (e.g. background remover). */
  prompt?: string;
  settings?: Partial<ComposerSettings>;
  /** lucide-react icon name, resolved by the Templates page's icon map. Used as a fallback when previewVideo/previewGif/previewImage isn't set. */
  icon: string;
  badge?: string;
  /** Looping muted preview clip shown on the card instead of the icon+gradient placeholder. Sourced from Pexels (free license, no attribution required). */
  previewVideo?: string;
  /** Animated GIF preview, self-hosted from /public/effects — the effect name is baked into the frame as a label. Takes priority over previewVideo/previewImage when set. */
  previewGif?: string;
  /** Static poster/fallback image, shown while previewVideo loads or when only a still is available. */
  previewImage?: string;
}

